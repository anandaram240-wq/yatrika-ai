// src/services/kannadaIntentExtractor.ts
import { resolveDestinationQuery, DestinationRecord } from '../data/destinationsRegistry';

export interface ExtractedTravelIntent {
  rawInput: string;
  recognizedOriginLabel: string;
  recognizedOriginStationCode: string;
  resolvedDestination: DestinationRecord | null;
  extractedDays: number;
  extractedBudgetPerPersonInr: number | null;
  governmentStayRequested: boolean;
  railRequested: boolean;
  detourRequested: boolean;
  aiGuardrailNotice: string;
}

export function parseKannadaOrEnglishTravelQuery(query: string): ExtractedTravelIntent {
  const q = query.trim();
  const lower = q.toLowerCase();

  // Origin detection (Kannada + English)
  let recognizedOriginLabel = 'KSR Bengaluru City Junction (SBC)';
  let recognizedOriginStationCode = 'SBC';
  if (q.includes('ಮೈಸೂರು') || lower.includes('mysuru') || lower.includes('mysore')) {
    if (lower.includes('from mys') || q.includes('ಮೈಸೂರಿನಿಂದ')) {
      recognizedOriginLabel = 'Mysuru Junction (MYS)';
      recognizedOriginStationCode = 'MYS';
    }
  } else if (q.includes('ಬೆಂಗಳೂರಿನಿಂದ') || lower.includes('from bengaluru') || lower.includes('from bangalore')) {
    recognizedOriginLabel = 'KSR Bengaluru City Junction (SBC)';
    recognizedOriginStationCode = 'SBC';
  }

  // Destination detection across Kannada & English tokens
  let resolvedDestination: DestinationRecord | null = null;
  const candidateTokens = ['ಹಂಪಿ', 'ಹಂಪಿಗೆ', 'hampi', 'ಮೈಸೂರು', 'mysuru', 'ಗೋಕರ್ಣ', 'gokarna', 'ಚಿಕ್ಕಮಗಳೂರು', 'chikkamagaluru', 'ಕೊಡಗು', 'ಮಡಿಕೇರಿ', 'madikeri', 'ಬಾದಾಮಿ', 'badami'];
  for (const token of candidateTokens) {
    if (lower.includes(token)) {
      resolvedDestination = resolveDestinationQuery(token === 'ಹಂಪಿಗೆ' ? 'ಹಂಪಿ' : token);
      if (resolvedDestination) break;
    }
  }

  // Duration detection (e.g., "ಎರಡು ದಿನದ" = 2 days, "two-day" = 2 days, "3 days" = 3)
  let extractedDays = 2;
  if (q.includes('ಎರಡು ದಿನ') || lower.includes('two-day') || lower.includes('2-day') || lower.includes('2 day')) {
    extractedDays = 2;
  } else if (q.includes('ಮೂರು ದಿನ') || lower.includes('three-day') || lower.includes('3 day')) {
    extractedDays = 3;
  } else if (q.includes('ಒಂದು ದಿನ') || lower.includes('one-day') || lower.includes('1 day')) {
    extractedDays = 1;
  }

  // Budget extraction (e.g., "₹5,000" or "5000")
  const budgetMatch = q.replace(/,/g, '').match(/(?:₹|rs\.?|inr|\b)(\d{3,6})\b/i);
  const extractedBudgetPerPersonInr = budgetMatch ? Number(budgetMatch[1]) : null;

  return {
    rawInput: q,
    recognizedOriginLabel,
    recognizedOriginStationCode,
    resolvedDestination,
    extractedDays,
    extractedBudgetPerPersonInr,
    governmentStayRequested:
      lower.includes('government') || lower.includes('kstdc') || q.includes('ಸರ್ಕಾರಿ'),
    railRequested: lower.includes('train') || lower.includes('hosapete') || q.includes('ರೈಲು'),
    detourRequested: lower.includes('along') || lower.includes('route') || lower.includes('near my road'),
    aiGuardrailNotice:
      'Intent extracted deterministically. All timetables, ASI entry fees, KSTDC registrations, and safety advisories are retrieved strictly from verified YatriKa registries—never generated by an LLM.',
  };
}
